export const getCropImage = (cropName: string): string => {
  if (!cropName) return "https://images.unsplash.com/photo-1592924357228-91a4daadcfea?w=700&auto=format&fit=crop&q=80";
  const normalized = cropName.toLowerCase().trim();

  if (CROP_IMAGES[normalized]) {
    return CROP_IMAGES[normalized];
  }

  // Word token matching
  const words = normalized.replace(/[()/\-,]/g, ' ').split(/\s+/).filter(w => w.length > 2);
  for (const w of words) {
    if (CROP_IMAGES[w]) {
      return CROP_IMAGES[w];
    }
  }

  // Substring match
  for (const [key, url] of Object.entries(CROP_IMAGES)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return url;
    }
  }

  return "https://images.unsplash.com/photo-1592924357228-91a4daadcfea?w=700&auto=format&fit=crop&q=80";
};
